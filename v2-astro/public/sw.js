/**
 * sw.js — Self-destruct and cache-purging Service Worker
 * Replaces any stale legacy precaching service worker (e.g. abhishek-raut-v*)
 * Unregisters itself, clears all CacheStorage keys, and claims clients immediately.
 */
self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(keys.map((key) => caches.delete(key)));
    }).then(() => {
      return self.registration.unregister();
    }).then(() => {
      return self.clients.claim();
    }).then(() => {
      // Reload active clients once caches are purged to serve fresh network assets
      return self.clients.matchAll({ type: 'window' }).then((clients) => {
        clients.forEach((client) => {
          if (client.url && 'navigate' in client) {
            client.navigate(client.url);
          }
        });
      });
    })
  );
});
